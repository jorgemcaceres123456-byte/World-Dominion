// Small, shared pixel motifs; every placeable silhouette is drawn at 40×40.
export function propArt(id, { rect: r, poly: p, line: l }) {
  const ink = "#4d514b",
    oak = "#947044",
    gold = "#d7b375",
    lime = "#a9bc75",
    wall = "#d5c4a2",
    shade = "#a19880",
    stone = "#849294",
    hi = "#bfc9b8";
  const foot = (x = 3, y = 32, w = 34) => {
    p(
      [
        [x, y],
        [x + w - 9, y - 3],
        [x + w, y],
        [x + w - 4, y + 4],
        [x + 6, y + 5],
      ],
      "#788364",
    );
  };
  const roof = (x, y, w, h, a = "#a45f4a", b = "#d49769") => {
    p(
      [
        [x - 2, y + 2],
        [x + w * 0.5, y - h - 1],
        [x + w + 2, y + 2],
      ],
      ink,
    );
    p(
      [
        [x - 1, y],
        [x + w * 0.5, y - h],
        [x + w + 1, y],
      ],
      a,
    );
    p(
      [
        [x, y],
        [x + w * 0.5, y - h],
        [x + w * 0.35, y],
      ],
      b,
    );
    l(x + 1, y - 1, x + w * 0.5, y - h, b);
  };
  const hut = (x, y, w, h, rc, hl) => {
    r(x, y, w, h, ink);
    r(x + 1, y, w - 3, h - 1, wall);
    r(x + w - 4, y, 3, h, shade);
    r(x + 3, y + 2, 2, h - 2, oak);
    r(x + 1, y + h - 4, w - 3, 1, oak);
    r(x + w / 2, y + h - 6, 4, 6, ink);
    r(x + w - 8, y + 3, 3, 3, "#c0a56e");
    roof(x, y, w, 8, rc, hl);
  };
  const log = (x, y) => {
    p(
      [
        [x, y],
        [x + 9, y - 5],
        [x + 14, y - 3],
        [x + 14, y],
        [x + 4, y + 6],
        [x, y + 3],
      ],
      "#805e41",
    );
    l(x + 1, y, x + 10, y - 4, gold, 2);
    r(x, y, 5, 4, "#c4a277");
    r(x + 2, y + 1, 2, 2, "#9b764a");
  };
  if (
    ["cottage", "granary", "sawmill", "forge", "chapel", "academy"].includes(id)
  ) {
    foot();
    if (id === "cottage") {
      hut(8, 19, 23, 14, "#9e6549", "#c59365");
      r(26, 9, 3, 7, shade);
      r(25, 8, 5, 2, hi);
      r(2, 31, 7, 3, "#709359");
      r(4, 28, 4, 4, "#9fb674");
    }
    if (id === "granary") {
      hut(6, 21, 26, 12, "#b49458", "#dfc77e");
      r(11, 16, 2, 16, "#977c4e");
      r(26, 17, 2, 16, "#977c4e");
      r(12, 23, 12, 7, "#a48958");
      for (let j = 0; j < 4; j++) r(13 + j * 3, 21, 1, 9, "#d4b777");
      r(27, 27, 9, 5, "#d8b463");
      r(29, 26, 5, 1, "#ecd18c");
    }
    if (id === "sawmill") {
      hut(5, 18, 23, 14, "#5f7964", "#92a885");
      r(25, 19, 4, 13, "#6b614d");
      r(28, 29, 8, 4, oak);
      p(
        [
          [25, 22],
          [29, 18],
          [33, 22],
          [31, 27],
          [27, 27],
        ],
        stone,
      );
      r(28, 22, 3, 2, hi);
      log(5, 32);
      log(14, 34);
    }
    if (id === "forge") {
      hut(3, 19, 24, 13, "#646e72", "#8e9895");
      r(7, 5, 5, 13, "#77837f");
      r(6, 4, 7, 3, "#a2aaa0");
      r(8, 1, 3, 2, "#b7bdac");
      r(11, 22, 9, 8, "#654c41");
      r(13, 25, 5, 4, "#de9954");
      r(15, 25, 2, 3, "#efc87a");
      p(
        [
          [24, 26],
          [38, 26],
          [35, 29],
          [32, 29],
          [32, 33],
          [36, 34],
          [36, 36],
          [24, 36],
          [24, 34],
          [28, 33],
          [28, 29],
        ],
        "#687b86",
      );
      r(25, 25, 12, 2, hi);
    }
    if (id === "chapel") {
      hut(5, 22, 23, 12, "#768294", "#a1a6a2");
      r(21, 11, 9, 22, wall);
      r(27, 11, 3, 22, shade);
      roof(21, 12, 9, 8, "#698190", "#99aca8");
      r(24, 1, 2, 7, gold);
      r(22, 3, 6, 2, gold);
      r(23, 16, 4, 5, "#6b8695");
      r(12, 23, 4, 4, "#92abb2");
    }
    if (id === "academy") {
      hut(2, 21, 25, 13, "#7b6688", "#ac89ac");
      r(24, 14, 9, 20, "#b6a98f");
      r(31, 14, 3, 20, shade);
      roof(22, 15, 13, 12, "#675d8a", "#9a86b3");
      r(27, 1, 3, 4, "#dec283");
      r(27, 20, 3, 5, "#9abdc3");
      r(9, 25, 3, 4, "#947fbc");
      r(17, 25, 3, 4, "#947fbc");
    }
    return true;
  }
  if (id === "windmill") {
    foot();
    p(
      [
        [11, 33],
        [16, 11],
        [24, 11],
        [29, 33],
      ],
      wall,
    );
    p(
      [
        [22, 12],
        [25, 12],
        [29, 33],
        [23, 33],
      ],
      shade,
    );
    roof(14, 14, 13, 7, "#986446", "#c49563");
    r(18, 26, 4, 7, ink);
    for (const [x, y] of [
      [6, 4],
      [34, 7],
      [31, 30],
      [7, 26],
    ]) {
      l(20, 17, x, y, "#735a42", 2);
      const dx = x - 20,
        dy = y - 17,
        n = Math.hypot(dx, dy),
        nx = (-dy / n) * 4,
        ny = (dx / n) * 4;
      p(
        [
          [x, y],
          [x + nx, y + ny],
          [20 + dx * 0.33 + nx, 17 + dy * 0.33 + ny],
          [20 + dx * 0.33, 17 + dy * 0.33],
        ],
        "#e2d3a4",
      );
      l(x, y, 20 + dx * 0.4, 17 + dy * 0.4, "#b9a477");
    }
    r(19, 16, 4, 4, "#9b7b50");
    return true;
  }
  if (id === "wheatfield") {
    p(
      [
        [2, 22],
        [23, 12],
        [38, 20],
        [17, 34],
        [2, 29],
      ],
      "#8f774e",
    );
    for (let y = 0; y < 3; y++)
      for (let j = 0; j < 6; j++) {
        let xx = 4 + j * 4 + y * 3,
          yy = 23 - j * 2 + y * 3;
        l(xx, yy + 2, xx + 1, yy - 6, "#c2a258");
        r(xx - 1, yy - 5, 2, 3, "#dfbd6a");
        r(xx + 1, yy - 8, 2, 4, "#eed28a");
      }
    return true;
  }
  if (id === "quarry" || id === "ruins") {
    foot();
    const colors = [
      ["#81908a", "#aeb5a5"],
      ["#939b89", "#c3c9ac"],
    ][id === "ruins" ? 1 : 0];
    for (let j = 0; j < 3; j++) {
      const x = 4 + j * 10,
        y = 25 + (j % 2) * 5,
        h = id === "ruins" ? (j === 1 ? 15 : 23) : 6 + j * 3;
      r(x, y - h, 7, h, colors[0]);
      r(x, y - h, 4, h - 1, colors[1]);
      r(x - 1, y - h - 2, 8, 3, colors[1]);
      r(x - 1, y - 1, 10, 3, "#79887c");
    }
    if (id === "quarry") {
      l(3, 14, 17, 5, oak, 2);
      l(13, 9, 19, 16, hi, 2);
      r(24, 28, 10, 5, oak);
      r(25, 33, 2, 2, ink);
      r(31, 33, 2, 2, ink);
    } else {
      r(3, 1, 11, 3, hi);
      r(7, 18, 2, 4, "#809c65");
      r(24, 21, 5, 3, "#9bb779");
    }
    return true;
  }
  if (id === "well" || id === "fountain") {
    foot(4, 33, 30);
    p(
      [
        [5, 24],
        [14, 20],
        [27, 20],
        [35, 24],
        [34, 31],
        [28, 34],
        [12, 34],
        [5, 30],
      ],
      stone,
    );
    p(
      [
        [6, 24],
        [15, 21],
        [26, 21],
        [33, 24],
        [26, 28],
        [14, 28],
      ],
      hi,
    );
    p(
      [
        [11, 24],
        [16, 22],
        [24, 22],
        [29, 24],
        [24, 26],
        [15, 26],
      ],
      "#6298a2",
    );
    r(9, 29, 6, 2, hi);
    r(23, 31, 7, 1, hi);
    if (id === "well") {
      r(9, 13, 2, 11, oak);
      r(28, 13, 2, 12, oak);
      roof(7, 14, 25, 9, "#99774e", "#cea46b");
      l(19, 14, 19, 23, gold);
      r(18, 21, 4, 4, "#798782");
    } else {
      r(18, 14, 4, 12, hi);
      r(16, 13, 8, 3, stone);
      l(19, 14, 16, 8, "#8dc6ce", 2);
      l(16, 9, 12, 16, "#a3d6d6");
      l(20, 13, 23, 6, "#99d3d3", 2);
      l(24, 6, 29, 17, "#b1d8cf");
    }
    return true;
  }
  if (id === "bazaar") {
    foot();
    r(6, 14, 2, 18, oak);
    r(31, 14, 2, 18, oak);
    p(
      [
        [3, 17],
        [10, 9],
        [30, 9],
        [37, 17],
        [34, 20],
        [6, 20],
      ],
      "#b56c5b",
    );
    for (let j = 0; j < 3; j++)
      p(
        [
          [8 + j * 9, 10],
          [12 + j * 8, 10],
          [10 + j * 9, 18],
          [5 + j * 10, 18],
        ],
        "#e3cd98",
      );
    r(6, 26, 27, 7, oak);
    r(5, 25, 30, 2, gold);
    for (let j = 0; j < 6; j++)
      r(
        7 + j * 4,
        23 - (j % 2),
        3,
        3,
        ["#d5895d", "#9cb372", "#d9b566"][j % 3],
      );
    return true;
  }
  if (id === "watchtower") {
    foot();
    r(11, 13, 17, 21, "#9a8664");
    r(11, 13, 4, 21, "#c0ab7c");
    r(24, 13, 4, 21, "#726c57");
    r(8, 13, 23, 4, oak);
    r(9, 8, 3, 7, oak);
    r(26, 8, 3, 7, oak);
    roof(6, 9, 27, 8, "#727d66", "#a2a584");
    r(17, 20, 4, 4, ink);
    r(18, 28, 5, 6, ink);
    return true;
  }
  if (id === "pier" || id === "woodbridge") {
    for (let j = 0; j < 8; j++) {
      const x = 2 + j * 4,
        y = 24 - j * 1.4;
      p(
        [
          [x, y],
          [x + 4, y - 1],
          [x + 9, y + 4],
          [x + 5, y + 6],
        ],
        j % 2 ? oak : "#b69566",
      );
    }
    for (let j = 0; j < 3; j++) {
      let x = 3 + j * 13,
        y = 25 - j * 4;
      r(x, y - 6, 2, 13, "#796147");
      r(x + 5, y, 2, 10, "#92754f");
    }
    if (id === "woodbridge") {
      l(3, 19, 30, 11, gold, 2);
      l(8, 25, 34, 17, oak, 2);
    } else {
      r(22, 17, 7, 6, "#bd925e");
      r(23, 19, 6, 1, "#795f45");
    }
    return true;
  }
  if (id === "camp") {
    p(
      [
        [2, 31],
        [16, 12],
        [28, 31],
      ],
      "#cdb484",
    );
    p(
      [
        [15, 12],
        [21, 10],
        [37, 27],
        [27, 31],
      ],
      "#ab8b6a",
    );
    p(
      [
        [9, 31],
        [16, 18],
        [22, 31],
      ],
      "#796753",
    );
    l(15, 11, 29, 32, "#ddc79d");
    r(26, 34, 7, 2, oak);
    r(28, 29, 3, 6, "#db954f");
    r(29, 32, 2, 3, "#efc96e");
    return true;
  }
  if (id === "runestone") {
    foot(6, 33, 25);
    p(
      [
        [8, 32],
        [12, 11],
        [20, 3],
        [27, 8],
        [31, 31],
        [25, 35],
        [13, 35],
      ],
      "#76818d",
    );
    p(
      [
        [11, 31],
        [14, 12],
        [20, 5],
        [23, 9],
        [21, 31],
      ],
      "#a4abb1",
    );
    l(16, 15, 23, 11, "#c8a2df", 2);
    l(22, 11, 18, 22, "#ab8ac7", 2);
    l(18, 22, 24, 19, "#d8b1eb", 2);
    return true;
  }
  if (["amber", "obsidian", "emerald", "ruby", "amethyst"].includes(id)) {
    const [a, b, h] = {
      amber: ["#ae793b", "#e0a653", "#ffe5a0"],
      obsidian: ["#414252", "#64617e", "#9b92ac"],
      emerald: ["#377b66", "#5ba784", "#b3dfb4"],
      ruby: ["#964c63", "#c5707d", "#efa4a2"],
      amethyst: ["#745b99", "#a17cc4", "#d7b3e4"],
    }[id];
    for (const [x, y, n] of [
      [5, 19, 11],
      [23, 15, 10],
      [13, 6, 13],
    ]) {
      p(
        [
          [x, y + 7],
          [x + n * 0.6, y],
          [x + n, y + 6],
          [x + n + 1, 30],
          [x + n * 0.5, 35],
          [x + 2, 30],
        ],
        b,
      );
      p(
        [
          [x + n * 0.6, y],
          [x + n, y + 6],
          [x + n + 1, 30],
          [x + n * 0.5, 35],
        ],
        a,
      );
      l(x + 2, y + 7, x + n * 0.55, y + 2, h, 2);
    }
    return true;
  }
  if (id === "reeds") {
    for (let j = 0; j < 7; j++) {
      let x = 5 + j * 4,
        y = 11 + (j % 3) * 4;
      l(x, 34, x - 2, y, "#72955b", 2);
      r(x - 3, y, 3, 6, oak);
      l(x, 33, x + 3, 22, lime);
    }
    return true;
  }
  if (id === "mushrooms") {
    for (const [x, y, n] of [
      [24, 22, 8],
      [5, 21, 8],
      [12, 12, 12],
    ]) {
      r(x + n / 2 - 1, y + 4, 3, 12, "#d3c7a4");
      p(
        [
          [x - 2, y + 6],
          [x, y + 2],
          [x + n / 2, y],
          [x + n, y + 2],
          [x + n + 2, y + 6],
          [x + n, y + 8],
          [x, y + 8],
        ],
        "#bd7767",
      );
      r(x + 2, y + 3, 3, 2, "#ead0ad");
    }
    return true;
  }
  if (id === "lotus") {
    p(
      [
        [2, 28],
        [9, 23],
        [23, 21],
        [36, 26],
        [31, 31],
        [17, 31],
        [15, 28],
        [13, 32],
        [4, 31],
      ],
      "#6f9d70",
    );
    for (const pts of [
      [
        [12, 20],
        [11, 13],
        [19, 20],
        [20, 25],
      ],
      [
        [17, 23],
        [20, 9],
        [23, 14],
        [23, 24],
      ],
      [
        [20, 25],
        [29, 13],
        [28, 21],
        [25, 25],
      ],
      [
        [10, 20],
        [17, 22],
        [20, 26],
        [14, 25],
      ],
    ])
      p(pts, "#d39bb1");
    r(18, 22, 5, 3, "#edcd87");
    return true;
  }
  if (["wolf", "boar", "sheep", "deer", "duck", "fox-wild"].includes(id)) {
    const [a, b, h] = {
      wolf: ["#788997", "#a3b0b3", "#c6ccc0"],
      boar: ["#78614c", "#9e8366", "#c2ab88"],
      sheep: ["#b7b5a5", "#e5dfc7", "#f6edce"],
      deer: ["#966c48", "#c39a68", "#e2c599"],
      duck: ["#c0bba4", "#ede6cf", "#f4edcf"],
      "fox-wild": ["#a65c42", "#d5915f", "#e5ceaa"],
    }[id];
    if (id === "duck") {
      p(
        [
          [4, 23],
          [11, 26],
          [20, 22],
          [25, 20],
          [29, 24],
          [27, 30],
          [18, 32],
          [9, 29],
        ],
        b,
      );
      r(23, 14, 6, 12, "#698e72");
      r(28, 18, 7, 3, "#d4a054");
      r(27, 16, 1, 2, ink);
      r(11, 25, 10, 2, a);
      r(14, 32, 4, 2, gold);
      return true;
    }
    for (const [x, y] of [
      [9, 28],
      [13, 27],
      [24, 27],
      [28, 26],
    ]) {
      r(x, y, 3, 7, a);
      r(x, y + 6, 3, 2, ink);
    }
    p(
      [
        [5, 23],
        [9, 19],
        [21, 18],
        [28, 15],
        [31, 19],
        [29, 25],
        [24, 29],
        [12, 30],
        [5, 27],
      ],
      b,
    );
    r(9, 20, 11, 2, h);
    p(
      [
        [23, 22],
        [26, 13],
        [30, 12],
        [34, 15],
        [37, 17],
        [36, 20],
        [32, 20],
        [28, 25],
      ],
      a,
    );
    r(30, 14, 4, 3, b);
    r(32, 15, 2, 1, ink);
    if (id === "deer") {
      l(28, 13, 26, 4, a, 2);
      l(26, 9, 22, 6, a, 2);
      l(31, 12, 33, 5, a, 2);
      l(32, 8, 36, 6, a);
      r(4, 19, 4, 4, h);
    }
    if (id === "sheep") {
      for (const [x, y] of [
        [6, 19],
        [10, 16],
        [17, 17],
        [21, 16],
      ])
        r(x, y, 7, 6, h);
      r(29, 11, 5, 4, b);
    }
    if (id === "boar") {
      r(8, 17, 15, 3, a);
      r(35, 18, 3, 2, b);
      r(33, 20, 3, 2, h);
    }
    if (id === "wolf" || id === "fox-wild") {
      p(
        [
          [27, 15],
          [27, 7],
          [32, 12],
          [34, 9],
          [34, 15],
        ],
        b,
      );
      p(
        [
          [8, 23],
          [2, 19],
          [1, 15],
          [3, 27],
          [9, 29],
        ],
        b,
      );
      r(2, 16, 3, 5, h);
      r(26, 20, 4, 4, h);
    }
    return true;
  }
  return false;
}
